import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';

const result = await build({
  entryPoints: ['supabase/edge-entry.ts'], bundle: true, write: false,
  format: 'esm', platform: 'neutral', target: 'es2022',
  external: ['@google/genai'],
  banner: { js: '// Generated by scripts/build-edge.mjs. No credentials are embedded.\nconst process = { env: { GEMINI_API_KEY: Deno.env.get("WAVEGUARD_GEMINI_API_KEY"), GEMINI_MODEL: Deno.env.get("WAVEGUARD_GEMINI_MODEL"), GEMINI_FALLBACK_MODELS: Deno.env.get("WAVEGUARD_GEMINI_FALLBACK_MODELS") } };' },
});
await mkdir('supabase/functions/waveguard-api', { recursive: true });
await writeFile('supabase/functions/waveguard-api/index.js', result.outputFiles[0].text.replace('from "@google/genai"', 'from "npm:@google/genai@2.31.0"'));
console.log('Built Supabase Edge Function from the shared Gemini validator.');
